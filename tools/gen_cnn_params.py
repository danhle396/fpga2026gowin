"""Sinh tham số RTL từ MỘT nguồn: quant_params.json + weights.mem + bias.mem + golden_vectors.npz (RA-01, R1).

Ghi vào project Gowin:
  src/cnn_params.vh       `define CNN_CONV1_SHIFT, CNN_CONV2_SHIFT (fpga_top.v và testbench cùng include)
  src/weights.mem, bias.mem   chép từ thư mục export nếu khác
  tb/vec_in.mem           20 cửa sổ x 768 byte, i = t*6 + c
  tb/vec_exp.mem          mỗi cửa sổ 5 từ 32 bit: logit0..3, class — tính bằng ml/src/golden_model.py

Dừng với mã lỗi khác 0 nếu golden model (đọc shift từ json) không khớp expected trong golden_vectors.npz,
hoặc json mâu thuẫn với phần cứng cố định của E1 (GAP >> 5, 3168 weight, 52 bias).

Chạy từ bất kỳ đâu:  python -I tools/gen_cnn_params.py [--export DIR] [--project DIR]
"""
import argparse
import json
import pathlib
import shutil
import sys

import numpy as np

sys.stdout.reconfigure(encoding="utf8")
ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "ml" / "src"))
from golden_model import forward  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("--export", default=ROOT / "FPGA_Fall_Detection_AI-20261012T141515Z-1-001"
                / "FPGA_Fall_Detection_AI" / "fpga_export", type=pathlib.Path)
ap.add_argument("--project", default=ROOT / "Document Board Kiwi Primer 20K" / "Kiwi20K_FallDetection_FPGA",
                type=pathlib.Path)
a = ap.parse_args()
ex, pj = a.export, a.project


def fail(msg):
    print("FAIL  " + msg)
    sys.exit(1)


q = json.loads((ex / "quant_params.json").read_text(encoding="utf8"))
s1, s2 = int(q["conv1_shift"]), int(q["conv2_shift"])
for name, s in (("conv1_shift", s1), ("conv2_shift", s2)):
    if not 0 <= s <= 31:
        fail(f"{name} = {s} không vừa cổng 5 bit của cnn_core")
if int(q["gap_shift"]) != 5:
    fail(f"gap_shift = {q['gap_shift']} nhưng gap_engine.v cố định >> 5")

W = np.array([int(v, 16) for v in (ex / "weights.mem").read_text().split()], dtype=np.int64)
B = np.array([int(v, 16) for v in (ex / "bias.mem").read_text().split()], dtype=np.int64)
if len(W) != q["weight_count"] or len(W) != 3168:
    fail(f"weights.mem có {len(W)} từ, json ghi {q['weight_count']}, E1 cần 3168")
if len(B) != q["bias_count"] or len(B) != 52:
    fail(f"bias.mem có {len(B)} từ, json ghi {q['bias_count']}, E1 cần 52")
W = np.where(W > 127, W - 256, W)
B = np.where(B >= 2**31, B - 2**32, B)
N1 = dict(w1=W[0:480].reshape(16, 6, 5), b1=B[0:16], w2=W[480:3040].reshape(32, 16, 5), b2=B[16:48],
          wd=W[3040:3168].reshape(4, 32), bd=B[48:52], n=[s1, s2], head="gap", score_shift=0)

d = np.load(ex / "golden_vectors.npz", allow_pickle=False)
X, E, C = d["input_windows"], d["expected_logits"], d["expected_classes"]
vin, vexp, ok = [], [], 0
for x, e, c in zip(X, E, C):
    cls, _, lg = forward(x, N1)
    ok += np.array_equal(lg, e) and cls == int(c)
    vin += [f"{int(v) & 0xFF:02X}" for v in x.reshape(-1)]
    vexp += [f"{int(v) & 0xFFFFFFFF:08X}" for v in lg] + [f"{cls:08X}"]
if ok != len(X):
    fail(f"golden với shift ({s1},{s2}) từ json chỉ khớp {ok}/{len(X)} expected của golden_vectors.npz")
print(f"PASS  golden (shift {s1},{s2} đọc từ quant_params.json) khớp golden_vectors.npz: {ok}/{len(X)}")

(pj / "src" / "cnn_params.vh").write_text(
    "// GENERATED by tools/gen_cnn_params.py from quant_params.json - DO NOT EDIT.\n"
    "// To change a shift: edit quant_params.json and rerun the script (RA-01).\n"
    "`ifndef CNN_PARAMS_VH\n"
    "`define CNN_PARAMS_VH\n"
    f"`define CNN_CONV1_SHIFT 5'd{s1}\n"
    f"`define CNN_CONV2_SHIFT 5'd{s2}\n"
    f"`define CNN_SCORE_SHIFT {int(q.get('score_shift', 0))}\n"
    "`endif\n", encoding="utf8", newline="\n")
print(f"ghi   src/cnn_params.vh: CONV1_SHIFT = {s1}, CONV2_SHIFT = {s2}, SCORE_SHIFT = {int(q.get('score_shift', 0))}")

for f in ("weights.mem", "bias.mem"):
    src, dst = ex / f, pj / "src" / f
    if not dst.exists() or src.read_bytes() != dst.read_bytes():
        shutil.copyfile(src, dst)
        print(f"chép  src/{f} từ export (bản cũ khác nguồn)")
    else:
        print(f"giữ   src/{f} (trùng từng byte với export)")

(pj / "tb").mkdir(exist_ok=True)
(pj / "tb" / "vec_in.mem").write_text("\n".join(vin) + "\n", newline="\n")
(pj / "tb" / "vec_exp.mem").write_text("\n".join(vexp) + "\n", newline="\n")
print(f"ghi   tb/vec_in.mem ({len(vin)} byte), tb/vec_exp.mem ({len(X)} vector x 5 từ)")
