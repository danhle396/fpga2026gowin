#!/usr/bin/env bash
# Thay mô hình trong bitstream 3 bằng N2 chỉ kênh đầu huấn luyện trên D1 11 người (seed 20261014, chọn trước khi xem kết quả).
#   bash docs/bao_cao/2026-10-16_n2_11_nguoi/run_bitstream3.sh <thư mục mô hình train_cnn.py> <thư mục làm việc ngoài repo>
# Các bước: lưu mô hình → export E2 P = 1 → tb_e2 50 vector → tb_proto 10 khung → P&R → netlist sau P&R (3 khung + 7 kịch bản)
#           → đáp án tự kiểm của firmware → Keil. Log của từng bước ghi vào thư mục báo cáo này.
set -eu
ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
M="$1"; W="$2"; B="$ROOT/docs/bao_cao/2026-10-16_n2_11_nguoi"
cd "$ROOT"
command -v iverilog >/dev/null || export PATH="/c/iverilog/bin:$PATH"
PY="$(command -v python3 || command -v python)"
mkdir -p "$W"

echo "== 1. lưu mô hình vào ml/out/n2_11_d1"
mkdir -p ml/out/n2_11_d1
cp "$M"/{fp32.npz,golden_vectors.npz,loso_params.npz,params_int8.npz,quant_params.json,report.txt} ml/out/n2_11_d1/

echo "== 2. export E2 P = 1"
"$PY" -I tools/export_mem.py --params ml/out/n2_11_d1/params_int8.npz --engine e2 --lanes 1 \
    --out ml/out/e2_matrix/n2_11_p1 | tee "$B/export_n2_11_p1.log" | tail -3

echo "== 3. tb_e2 (bản sao ngoài repo)"
rm -rf "$W/tbe2"; cp -r ml/out/e2_matrix/n2_11_p1 "$W/tbe2"
bash rtl/e2/run_tb_e2.sh "$W/tbe2" 50 > "$B/tb_e2_n2_11_p1.log"; grep -E "KET QUA|^(PASS|FAIL)" "$B/tb_e2_n2_11_p1.log"

echo "== 4. tb_proto RTL, 10 khung + 7 kịch bản"
bash rtl/v3/run_tb_proto.sh --e2 ml/out/e2_matrix/n2_11_p1 --ng 10 --work "$W/proto" > "$B/tb_proto_n2_11_p1.log" 2>&1
grep -E "^(PASS|FAIL)" "$B/tb_proto_n2_11_p1.log" | tail -1

echo "== 5. P&R bitstream (bản phát hành, không tùy chọn netlist)"
bash rtl/v3/pnr_v3.sh "$W/pnr" e2 ml/out/e2_matrix/n2_11_p1 > "$B/pnr_b3.log" 2>&1
tail -12 "$B/pnr_b3.log" | grep -E "Logic|BSRAM|DSP|Max Freq" | cut -c1-160

echo "== 6. netlist sau P&R, 3 khung + 7 kịch bản"
bash rtl/gl/run_gl.sh "$W/gl" ml/out/e2_matrix/n2_11_p1 3 > "$B/gl_b3.log" 2>&1
grep -E "FF có INIT|^ +[0-9]+ |^(PASS|FAIL)" "$B/gl_b3.log" | tail -12
n=$(diff <(tr -d '\r' < "$W/pnr/impl/pnr/fpga_project.fs" | grep -v "Created Time") \
         <(tr -d '\r' < "$W/gl/pnr/impl/pnr/fpga_project.fs" | grep -v "Created Time") | wc -l)
echo "bản phát hành và bản đã mô phỏng netlist khác $n dòng (phải 0)"

echo "== 7. đáp án tự kiểm cho firmware (FW_BITSTREAM 3)"
{ echo "/* GENERATED by tools/export_mem.py --params ml/out/n2_11_d1/params_int8.npz --engine e2 --lanes 1 - DO NOT EDIT. Đáp án tự kiểm A.10 (SEQ 0xEE) cho bitstreams/3_v3_e2_n2. */"
  tail -n +2 ml/out/e2_matrix/n2_11_p1/selftest_expect.h; } > firmware/src/selftest_expect_v3_e2_n2.h
cat firmware/src/selftest_expect_v3_e2_n2.h
echo "xong các bước tự động; còn: chép .fs/rpt/cnn_params.vh vào bitstreams/3_v3_e2_n2, SHA256, Keil, tài liệu"
